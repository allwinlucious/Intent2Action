"""Training on Kaggle (2 x T4) in parallel with the local sim work; runs detached like supervisor.py.

  setsid nohup .venv-ml/bin/python learn/kaggle_lane.py > logs/learn/kaggle_lane.out 2>&1 &

Per batch, once its inputs are done (logs/learn/done/<step>): build a bundle (code, a stub agent module with
the system prompt and tool schemas, data, earlier outputs incl. checkpoints), upload it as a new version of
a new private dataset <user>/robot-learn-<batch>-<time> (a new version of one dataset raced: the notebook
mounted the previous version), push the notebook <user>/robot-learn-<batch> (learn/kaggle_job.py),
wait, download its outputs into runs/, and mark the steps whose outputs arrived as done. A batch that ends
before all its outputs exist (12 h session limit) runs again and resumes from its checkpoints.
"""

import datetime
import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOG = ROOT / "logs/learn"
KAGGLE = str(ROOT / ".venv-ml/bin/kaggle")
USER = "allwinlucious"
BUNDLE = ROOT / "runs/kaggle_bundle"
POLL_S = 120
RETRIES = 3
CODE = ["train_trl.py", "sft.py", "qwen.py", "head.py", "kaggle_job.py"]
S1, S2 = "logs/learn/stage1_train.jsonl", "logs/learn/expert_train.jsonl"

BATCHES = [
    {"name": "k1", "needs": ["collect_stage1"], "data": [S1], "runs": ["b_sft", "feat_s1.pt*", "c1"],
     "jobs": {"0": [[["learn/train_trl.py", "sft", "--stage1", S1, "--epochs", "1", "--limit", "600", "--out", "runs/b_sft"],
                     "runs/b_sft/adapter_model.safetensors"]],
              "1": [[["learn/head.py", "featurize", "--stage1", S1, "--out", "runs/feat_s1.pt"], "runs/feat_s1.pt"],
                    [["learn/head.py", "train", "--features", "runs/feat_s1.pt", "--out", "runs/c1"], "runs/c1/head.pt"]]},
     "produces": {"train_b_sft": "runs/b_sft/adapter_model.safetensors", "train_c1": "runs/c1/head.pt"}},
    {"name": "k2", "needs": ["expert_train", "train_b_sft", "train_c1"], "data": [S1, S2],
     "runs": ["b_sft", "feat_s1.pt", "c1", "b_sft2", "feat_s2.pt*", "c2"],
     "jobs": {"0": [[["learn/train_trl.py", "sft", "--stage1", S1, "--stage2", S2, "--init", "runs/b_sft", "--epochs", "1",
                      "--limit", "400", "--out", "runs/b_sft2"], "runs/b_sft2/adapter_model.safetensors"]],
              "1": [[["learn/head.py", "featurize", "--stage2", S2, "--out", "runs/feat_s2.pt"], "runs/feat_s2.pt"],
                    [["learn/head.py", "train", "--features", "runs/feat_s2.pt", "--replay-from", "runs/feat_s1.pt",
                      "--init", "runs/c1", "--out", "runs/c2"], "runs/c2/head.pt"]]},
     "produces": {"train_b_sft2": "runs/b_sft2/adapter_model.safetensors", "train_c2": "runs/c2/head.pt"}},
]


def log(message: str) -> None:
  line = f"{datetime.datetime.now():%Y-%m-%d %H:%M:%S} {message}"
  print(line, flush=True)
  with open(LOG / "kaggle_lane.log", "a") as f:
    f.write(line + "\n")


def kaggle(*args: str) -> str:
  done = subprocess.run([KAGGLE, *args], capture_output=True, text=True)
  return done.stdout + done.stderr


def done(step: str) -> bool:
  return (LOG / "done" / step).exists()


def stub_agent() -> str:
  """agent.py for Kaggle: the system prompt and tool schemas without the robot stack modules."""
  sys.path.insert(0, str(ROOT / "learn"))
  import agent
  return (f'"""Stub of learn/agent.py for training off the robot stack (generated by kaggle_lane.py)."""\n'
          f"SYSTEM = {agent.SYSTEM!r}\n_SPECS = {json.dumps(agent.tool_specs())!r}\n\n\n"
          "def tool_specs():\n  import json\n  return json.loads(_SPECS)\n")


def build(batch: dict) -> str:
  shutil.rmtree(BUNDLE, ignore_errors=True)
  (BUNDLE / "learn").mkdir(parents=True)
  (BUNDLE / "logs/learn").mkdir(parents=True)
  for name in CODE:
    shutil.copy(ROOT / "learn" / name, BUNDLE / "learn" / name)
  (BUNDLE / "learn/agent.py").write_text(stub_agent())
  for path in batch["data"]:
    shutil.copy(ROOT / path, BUNDLE / path)
  for pattern in batch["runs"]:
    for path in (ROOT / "runs").glob(pattern):
      target = BUNDLE / "runs" / path.name
      target.parent.mkdir(exist_ok=True)
      (shutil.copytree if path.is_dir() else shutil.copy)(path, target)
  (BUNDLE / "jobs.json").write_text(json.dumps(batch["jobs"]))
  slug = f"robot-learn-{batch['name']}-{datetime.datetime.now():%m%d%H%M%S}"
  (BUNDLE / "dataset-metadata.json").write_text(json.dumps(
      {"title": slug, "id": f"{USER}/{slug}", "licenses": [{"name": "other"}]}))
  return f"{USER}/{slug}"


def upload(dataset: str) -> None:
  log(f"upload {dataset}: {kaggle('datasets', 'create', '-p', str(BUNDLE), '--dir-mode', 'zip').strip()[-200:]}")
  for _ in range(60):  # processed before the notebook can mount it
    if "ready" in kaggle("datasets", "status", dataset).lower():
      return
    time.sleep(20)
  raise RuntimeError(f"dataset {dataset} not ready after 20 min")


def push(batch: dict, dataset: str) -> str:
  kernel = BUNDLE.parent / f"kaggle_kernel_{batch['name']}"
  shutil.rmtree(kernel, ignore_errors=True)
  kernel.mkdir()
  shutil.copy(ROOT / "learn/kaggle_job.py", kernel / "kaggle_job.py")
  kid = f"{USER}/robot-learn-{batch['name']}"
  (kernel / "kernel-metadata.json").write_text(json.dumps({
      "id": kid, "title": f"robot-learn-{batch['name']}", "code_file": "kaggle_job.py", "language": "python",
      "kernel_type": "script", "is_private": "true", "enable_gpu": "true", "enable_internet": "true",
      "machine_shape": "NvidiaTeslaT4", "dataset_sources": [dataset], "competition_sources": [], "kernel_sources": []}))
  log(f"push {kid}: {kaggle('kernels', 'push', '-p', str(kernel)).strip()[-200:]}")
  return kid


def wait(kid: str) -> str:
  time.sleep(POLL_S)
  while True:
    status = kaggle("kernels", "status", kid)
    if any(s in status.lower() for s in ("complete", "error", "cancel")):
      return status.strip()
    time.sleep(POLL_S)


def fetch(batch: dict, kid: str) -> None:
  target = ROOT / f"runs/kaggle_out_{batch['name']}"
  shutil.rmtree(target, ignore_errors=True)
  target.mkdir(parents=True)
  kaggle("kernels", "output", kid, "-p", str(target))
  status = target / "out/status.json"
  log(f"{batch['name']} status: {status.read_text() if status.exists() else 'no status.json'}")
  if (target / "out/runs").is_dir():
    shutil.copytree(target / "out/runs", ROOT / "runs", dirs_exist_ok=True)
  for path in (target / "out/logs").glob("*.log"):
    shutil.copy(path, LOG / "steps" / f"kaggle_{batch['name']}_{path.name}")
  for step, path in batch["produces"].items():
    if (ROOT / path).exists():
      (LOG / "done" / step).touch()
      log(f"done {step} (Kaggle)")


def main() -> None:
  (LOG / "done").mkdir(parents=True, exist_ok=True)
  (LOG / "steps").mkdir(parents=True, exist_ok=True)
  log(f"start; quota: {' '.join(kaggle('quota').split())}")
  for batch in BATCHES:
    attempts = 0
    while not all(done(s) for s in batch["produces"]):
      while not all(done(s) for s in batch["needs"]):
        time.sleep(60)
      if attempts > RETRIES:
        log(f"FAILED batch {batch['name']} after {attempts} runs")
        break
      attempts += 1
      try:
        dataset = build(batch)
        upload(dataset)
        kid = push(batch, dataset)
        log(f"{batch['name']} finished: {wait(kid)}")
        fetch(batch, kid)
      except Exception as error:  # pylint: disable=broad-except
        log(f"{batch['name']} run {attempts}: {error!r}")
        time.sleep(300)
  log(f"all batches handled; quota: {' '.join(kaggle('quota').split())}")


if __name__ == "__main__":
  sys.exit(main())
